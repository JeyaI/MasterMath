"""The puzzle catalog: everything scraped, mostly never used.

    catalog/sources.yaml       registry of sources (where, license, which parser)
    catalog/<source>.jsonl     one puzzle per line; regenerated by `ms sources add`
    catalog/annotations.yaml   judgements about puzzles: visual_potential, tags, skip, notes

The split matters: re-scraping rewrites the .jsonl but never touches a judgement
that already exists in annotations.yaml. A heuristic fills in missing entries
(scored_by: heuristic); anything you edit by hand should say scored_by: human.
"""
from __future__ import annotations

import json
import re
import urllib.request
from pathlib import Path

from ruamel.yaml.comments import CommentedMap

from . import paths, yamlio
from .sources import PARSERS


# --- registry & raw files ---------------------------------------------------------------
def sources() -> dict:
    p = paths.catalog() / "sources.yaml"
    return dict(yamlio.load(p)) if p.exists() else {}


def fetch(source_id: str, refresh: bool = False) -> str:
    src = sources()[source_id]
    raw = paths.cache() / "raw" / f"{source_id}.txt"
    if refresh or not raw.exists():
        raw.parent.mkdir(parents=True, exist_ok=True)
        req = urllib.request.Request(src["url"], headers={"User-Agent": "mathshorts/0.1 (personal use)"})
        with urllib.request.urlopen(req, timeout=60) as r:
            raw.write_bytes(r.read())
    return raw.read_text(encoding="utf-8", errors="replace")


# --- records --------------------------------------------------------------------------
def jsonl_path(source_id: str) -> Path:
    return paths.catalog() / f"{source_id}.jsonl"


def write_records(source_id: str, records: list[dict]) -> Path:
    p = jsonl_path(source_id)
    text = "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in sorted(records, key=lambda r: r["number"]))
    yamlio.write_atomic(p, text)
    return p


def records() -> list[dict]:
    out = []
    for p in sorted(paths.catalog().glob("*.jsonl")):
        out += [json.loads(l) for l in p.read_text(encoding="utf-8").splitlines() if l.strip()]
    return out


def get(record_id: str) -> dict:
    for r in records():
        if r["id"] == record_id:
            return r
    raise SystemExit(f"ms: no catalog record {record_id!r} (try `ms suggest` or `ms sources list`)")


# --- annotations ----------------------------------------------------------------------
def annotations_path() -> Path:
    return paths.catalog() / "annotations.yaml"


def annotations():
    p = annotations_path()
    if p.exists():
        data = yamlio.load(p)
        if data is not None:
            return data
    return CommentedMap()


# Section keywords -> (tag, base visual score). First match wins; checked against section name.
SECTION_RULES = [
    ("greek cross", "dissection", 5), ("dissection", "dissection", 5), ("patchwork", "dissection", 4),
    ("geometrical", "geometry", 4), ("points and lines", "geometry", 4), ("chess", "chessboard", 4),
    ("moving counter", "counters", 4), ("unicursal", "routes", 4), ("route", "routes", 4),
    ("maze", "mazes", 4), ("magic", "magic-squares", 3), ("combination", "combinatorics", 3),
    ("crossing river", "logic", 3), ("measuring", "measuring", 3), ("games", "games", 3),
    ("clock", "clocks", 3), ("locomotion", "speed", 2), ("speed", "speed", 2), ("digital", "digits", 2),
    ("age and kinship", "age", 1), ("money", "money", 1), ("paradox", "paradox", 2),
]
VISUAL_WORDS = re.compile(r"\b(cut|pieces|square|triangle|circle|diagram|board|counters?|route|path|"
                          r"line|figure|shape|fold|cross|tiles?|grid|matches)\b", re.I)
WORDY_WORDS = re.compile(r"(shillings?|pence|\bs\.\s*\d|\bd\.\b|£|pounds?|farthings?|years old|"
                         r"his age|her age|wages|interest)", re.I)


def heuristic(record: dict) -> CommentedMap:
    """Cheap first-pass judgement from section + keywords. Meant to be overridden by a human."""
    section = (record.get("section") or "").lower()
    tag, score = None, 3
    for key, t, s in SECTION_RULES:
        if key in section:
            tag, score = t, s
            break
    text = record.get("text") or ""
    visual_hits, wordy_hits = len(VISUAL_WORDS.findall(text)), len(WORDY_WORDS.findall(text))
    if record.get("has_figure"):
        score += 1
    if visual_hits >= 4:
        score += 1
    if wordy_hits >= 2:
        score -= 1
    if not record.get("solution"):
        score -= 1                                  # we can still use it, but we must solve it ourselves
    m = CommentedMap()
    m["visual_potential"] = max(1, min(5, score))
    m["tags"] = [tag] if tag else []
    m["scored_by"] = "heuristic"
    return m


def merge_heuristics(recs: list[dict]) -> int:
    """Add heuristic annotations for records that have none. Never overwrites. Returns count added."""
    ann = annotations()
    added = 0
    for r in recs:
        if r["id"] not in ann:
            ann[r["id"]] = heuristic(r)
            added += 1
    if added:
        ordered = CommentedMap()
        for k in sorted(ann):
            ordered[k] = ann[k]
        header = ("# Judgements about catalog puzzles. Edit freely; set scored_by: human on anything\n"
                  "# you change so it's clear a person looked. Fields: visual_potential (1-5), tags,\n"
                  "# skip (true = never suggest), notes. Re-scraping never overwrites entries here.\n")
        yamlio.write_atomic(annotations_path(), header + yamlio.dump_str(ordered))
    return added


def add_source(source_id: str, file: Path | None = None, refresh: bool = False) -> dict:
    srcs = sources()
    if source_id not in srcs:
        raise SystemExit(f"ms: unknown source {source_id!r}; registered: {', '.join(srcs)}")
    text = file.read_text(encoding="utf-8", errors="replace") if file else fetch(source_id, refresh)
    recs = PARSERS[srcs[source_id]["parser"]](text, source_id)
    if not recs:
        raise SystemExit(f"ms: parser found no puzzles in {source_id}; check the raw file format")
    path = write_records(source_id, recs)
    added = merge_heuristics(recs)
    return {"path": path, "puzzles": len(recs), "with_solution": sum(1 for r in recs if r["solution"]),
            "with_figure": sum(1 for r in recs if r["has_figure"]), "annotations_added": added,
            "sections": sorted({r["section"] for r in recs if r["section"]})}
